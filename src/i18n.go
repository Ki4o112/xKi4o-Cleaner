// T returns the text for key in the current language.
func T(key string, args ...any) string {
	v, ok := texts[key]
	if !ok {
		return key
	}
	s := v[0]
	if lang.Load() == "en" {
		s = v[1]
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}
