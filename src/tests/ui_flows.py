def check(name, ok, info=""):
    results.append((name, ok)); print(("PASS " if ok else "FAIL ") + name + (" — " + str(info) if info and not ok else ""))

def fast(q, splash=False):
    # the splash runs about 5 s for the show; the page tests skip it (one test keeps the real length)
    return q if splash else q + ("&" if "?" in q else "?") + "fastsplash=1"

async def page(b, q="", w=1180, h=820, start="clean", splash=False):
    q = fast(q, splash)
    pg = await b.new_page(viewport={"width": w, "height": h})
    pg.errs = []
    pg.on("pageerror", lambda e: pg.errs.append(str(e)))
    pg.on("console", lambda m: pg.errs.append("console:" + m.text) if m.type == "error" else None)
    await pg.add_init_script("""window.__long=[];window.__longLoad=[];try{new PerformanceObserver(l=>l.getEntries().forEach(e=>(e.startTime<600?window.__longLoad:window.__long).push(e.duration))).observe({type:'longtask',buffered:true});}catch(e){}""")
    await pg.goto(BASE + q)
    if start:  # the app opens on "PC health"; most checks start from a page of their own
        await pg.evaluate("p => go(p)", start)
    return pg

# The Go bindings as go-webview2 defines them (window[name] and window.__go[name]),
# answered by the page's own mock: the page then runs as it does in the real app
# ("native"), including a page function that has a binding's name.
BINDINGS = re.findall(r'^\s*"(\w+)":\s', (lambda t: t[t.index("binds := map"):t.index("for name, f := range binds")])(
    (pathlib.Path(__file__).resolve().parent.parent / "main_windows.go").read_text(encoding="utf-8")), re.M)
NATIVE_JS = """(names => { window.__calls = [];
  for (const name of names) {
    window[name] = function () {
      const args = JSON.parse(JSON.stringify(Array.prototype.slice.call(arguments)));
      window.__calls.push(name);
      return new Promise((resolve, reject) => setTimeout(async () => {
        try { const m = window.__mock; const r = m && m[name] ? await m[name](...args) : null; resolve(r === undefined ? null : JSON.parse(JSON.stringify(r))); }
        catch (e) { reject(String(e)); }
      }, 0));
    };
    (window.__go = window.__go || {})[name] = window[name];
  } })(%s)"""

async def native_page(b, q=""):
    q = fast(q)
    pg = await b.new_page(viewport={"width": 1180, "height": 820})
    pg.errs = []
    pg.on("pageerror", lambda e: pg.errs.append(str(e)))
    pg.on("console", lambda m: pg.errs.append("console:" + m.text) if m.type == "error" else None)
    await pg.add_init_script(NATIVE_JS % json.dumps(BINDINGS))
    await pg.goto(BASE + q)
    await pg.evaluate("go('clean')")
    return pg

